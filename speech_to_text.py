# Transcrire le fichier audio local téléchargé
result = pipe("Es.mp3", return_timestamps=True)  # Add return_timestamps=True
print("Transcription :", result["text"])

# Enregistrer la transcription dans un fichier texte
with open("Es.mp3", "w", encoding="utf-8") as f:
    f.write(result["text"])

