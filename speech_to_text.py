import torch
from transformers import AutoProcessor, AutoModelForSpeechSeq2Seq, pipeline
from datasets import load_dataset

# Configurer le dispositif (GPU si disponible) et le type de données
device = 0 if torch.cuda.is_available() else -1  # 0 pour le premier GPU, -1 pour CPU
torch_dtype = torch.float16 if torch.cuda.is_available() else torch.float32

# Identifier le modèle
model_id = "openai/whisper-large-v3-turbo"

# Charger le modèle et le processeur
processor = AutoProcessor.from_pretrained(model_id)
model = AutoModelForSpeechSeq2Seq.from_pretrained(
    model_id,
    torch_dtype=torch_dtype,
    low_cpu_mem_usage=True,
    use_safetensors=True  # Optionnel, améliore la vitesse de chargement
)

# Déplacer le modèle vers le dispositif approprié
if torch.cuda.is_available():
    model.to("cuda")

# Créer le pipeline pour la reconnaissance automatique de la parole
pipe = pipeline(
    "automatic-speech-recognition",
    model=model,
    tokenizer=processor.tokenizer,
    feature_extractor=processor.feature_extractor,
    torch_dtype=torch_dtype,
    device=device,  # Utilise GPU si disponible
)

from google.colab import drive
